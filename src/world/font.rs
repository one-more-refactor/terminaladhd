// Guillemets flank the selector word on the horizon weld; the chrome face has
// no punctuation otherwise, so the two chevrons are carried here directly.
const CHEV_L: [u8; 7] = [0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02];
const CHEV_R: [u8; 7] = [0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08];

pub fn glyph(c: char) -> [u8; 7] {
    let c = c.to_ascii_uppercase();
    if c.is_ascii_alphabetic() {
        UPPER[(c as u8 - b'A') as usize]
    } else if c.is_ascii_digit() {
        DIGIT[(c as u8 - b'0') as usize]
    } else {
        match c {
            '<' | '‹' => CHEV_L,
            '>' | '›' => CHEV_R,
            _ => SPACE,
        }
    }
}
